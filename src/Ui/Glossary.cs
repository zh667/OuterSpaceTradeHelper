        public static void Apply<T>(List<Column<T>> cols, string page = null)
        {
            foreach (var c in cols)
            {
                if (c == null || !string.IsNullOrEmpty(c.tip) || string.IsNullOrEmpty(c.title)) continue;
                string s;
                if (page != null && PageColumns.TryGetValue(page + "|" + c.title, out s)) c.tip = s;
                else if (Columns.TryGetValue(c.title, out s)) c.tip = s;
            }
        }

